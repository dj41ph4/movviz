const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "_locales");
const refKeys = Object.keys(dict.fr).sort().join();
for (const [lang, messages] of Object.entries(dict)) {
  if (Object.keys(messages).sort().join() !== refKeys) throw new Error(`Clés incohérentes pour ${lang}`);
  const out = {};
  for (const [key, message] of Object.entries(messages)) {
    out[key] = { message: message.replace("$1", "$USER$") };
    if (message.includes("$1")) out[key].placeholders = { user: { content: "$1" } };
  }
  fs.mkdirSync(path.join(root, lang), { recursive: true });
  fs.writeFileSync(path.join(root, lang, "messages.json"), JSON.stringify(out, null, 2) + "\n");
}
