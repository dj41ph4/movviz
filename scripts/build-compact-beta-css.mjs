// Generates src/components/appearance/design-beta-compact.generated.css.
//
// The Beta design sheets (salle-obscure, premium, design-beta) are written
// for desktop (≥1024px) and mix two things: the theme (palette, surfaces,
// borders, shadows, typography) and the desktop geometry (sizes, spacing,
// positions). Phones and tablets need the same theme without that geometry,
// so this script copies only the theme declarations of every desktop rule
// into a `max-width: 1023.98px` block. Run it after editing those sheets:
//   node scripts/build-compact-beta-css.mjs
import { readFile, writeFile } from "node:fs/promises";
import postcss from "postcss";

const SOURCES = ["premium.css", "salle-obscure.css", "design-beta.css"]; // same order as AppearanceProvider imports them
const DIR = new URL("../src/components/appearance/", import.meta.url);
const OUT = new URL("design-beta-compact.generated.css", DIR);

/** Theme-only properties: never change size, spacing, position or flow. */
const THEME = /^(--[\w-]+|color|background(-color|-image)?|border(-(top|right|bottom|left))?-color|border-radius|border-(top|bottom)-(left|right)-radius|box-shadow|text-shadow|font-family|font-weight|font-style|font-variant-numeric|font-optical-sizing|letter-spacing|text-wrap|accent-color|caret-color|fill|stroke|stroke-width|outline-color|backdrop-filter|-webkit-backdrop-filter|opacity|filter)$/;

function isDesktopOnly(node) {
  for (let p = node.parent; p; p = p.parent) {
    if (p.type === "atrule" && p.name === "media") {
      // Hover-only and reduced-motion variants stay desktop: they tune
      // pointer interactions that phones and tablets do not have.
      return p.params.trim() === "(min-width: 1024px)";
    }
  }
  return false;
}

export async function buildCompactBetaCss() {
  const out = postcss.root();
  const block = postcss.atRule({ name: "media", params: "(max-width: 1023.98px)" });
  for (const file of SOURCES) {
    const css = await readFile(new URL(file, DIR), "utf8");
    postcss.parse(css).walkRules((rule) => {
      if (!isDesktopOnly(rule) || rule.parent?.type === "rule") return;
      const decls = rule.nodes.filter((n) => n.type === "decl" && THEME.test(n.prop));
      if (decls.length === 0) return;
      block.append(postcss.rule({ selector: rule.selector, nodes: decls.map((d) => d.clone()) }));
    });
  }
  out.append(block);
  return `/* GENERATED by scripts/build-compact-beta-css.mjs from ${SOURCES.join(", ")}.
   Do not edit: Beta theme (palette, surfaces, typography) for phones and
   tablets, without the desktop geometry. Layout fixes live in design-beta-compact.css. */
${out.toString()}
`;
}

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, "/")}` || process.argv[1]?.endsWith("build-compact-beta-css.mjs")) {
  await writeFile(OUT, await buildCompactBetaCss());
  console.log("design-beta-compact.generated.css written");
}
