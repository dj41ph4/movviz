import assert from "node:assert/strict";
import { test } from "node:test";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";
import { NextRequest } from "next/server";
const dir = fs.mkdtempSync(path.join(os.tmpdir(), "movviz-reset-safety-"));
process.env.MOVVIZ_CONFIG_DIR = dir;
process.env.MOVVIZ_DATA_DIR = dir;
const { addUser, createSession, hasAnyUser } = await import("../src/lib/auth/store.ts");
const { POST } = await import("../src/app/api/system/reset/route.ts");
const { stageResetStores, recoverInterruptedResets } = await import("../src/lib/system/resetStores.ts");
test("interrupted reset restores staged settings without touching media", () => {
  const fixture = fs.mkdtempSync(path.join(os.tmpdir(), "movviz-reset-recovery-"));
  const settings = path.join(fixture, "users.json");
  fs.writeFileSync(settings, "accounts");
  fs.writeFileSync(path.join(fixture, "film.mkv"), "video");
  stageResetStores(fixture, [settings]);
  assert.equal(fs.existsSync(settings), false);
  recoverInterruptedResets(fixture);
  assert.equal(fs.readFileSync(settings, "utf8"), "accounts");
  assert.equal(fs.readFileSync(path.join(fixture, "film.mkv"), "utf8"), "video");
});
test("reset clears library and accounts without deleting media in the same directory", async () => {
  fs.mkdirSync(path.join(dir, "media"));
  fs.writeFileSync(path.join(dir, "media", "film.mkv"), "media");
  fs.writeFileSync(path.join(dir, "library-movies.json"), "[]");
  fs.writeFileSync(path.join(dir, "unrelated.json"), "user file");
  fs.mkdirSync(path.join(dir, "avatars"));
  fs.writeFileSync(path.join(dir, "avatars", "admin.png"), "avatar");
  fs.writeFileSync(path.join(dir, "avatars", "family-video.mkv"), "video");
  fs.mkdirSync(path.join(dir, "context"));
  const contextFile = path.join(dir, "context", "user-context.sqlite");
  const context = new DatabaseSync(contextFile);
  context.exec("CREATE TABLE context_events (id TEXT); INSERT INTO context_events VALUES ('old-history')");
  context.close();
  addUser({ id: "admin", username: "admin", role: "admin", status: "approved", createdAt: Date.now() } as never);
  const session = createSession("admin").token;
  const originalFetch = globalThis.fetch;
  try {
    globalThis.fetch = async () => Response.json({ error: "busy" }, { status: 503 });
    const blocked = await POST(new NextRequest("http://localhost/api/system/reset", { method: "POST", headers: { cookie: `movviz_session=${session}` } }));
    assert.equal(blocked.status, 409);
    assert.equal(hasAnyUser(), true);
    assert.equal(fs.existsSync(path.join(dir, "users.json")), true, "pending account writes must survive a failed reset");
    assert.equal(fs.existsSync(path.join(dir, "library-movies.json")), true);
    globalThis.fetch = async () => Response.json({ ok: true });
    fs.renameSync(contextFile, `${contextFile}.backup`);
    fs.writeFileSync(contextFile, "invalid database");
    const invalidDb = await POST(new NextRequest("http://localhost/api/system/reset", { method: "POST", headers: { cookie: `movviz_session=${session}` } }));
    assert.equal(invalidDb.status, 500);
    assert.equal(hasAnyUser(), true, "a database failure must restore account files");
    assert.equal(fs.existsSync(path.join(dir, "library-movies.json")), true);
    fs.unlinkSync(contextFile);
    fs.renameSync(`${contextFile}.backup`, contextFile);
    const response = await POST(new NextRequest("http://localhost/api/system/reset", { method: "POST", headers: { cookie: `movviz_session=${session}` } }));
    assert.equal(response.status, 200);
    assert.equal(hasAnyUser(), false);
    assert.equal(fs.existsSync(path.join(dir, "library-movies.json")), false);
    assert.equal(fs.readFileSync(path.join(dir, "media", "film.mkv"), "utf8"), "media");
    assert.equal(fs.readFileSync(path.join(dir, "unrelated.json"), "utf8"), "user file");
    assert.equal(fs.existsSync(path.join(dir, "avatars", "admin.png")), false);
    assert.equal(fs.readFileSync(path.join(dir, "avatars", "family-video.mkv"), "utf8"), "video");
    const cleared = new DatabaseSync(contextFile);
    assert.equal((cleared.prepare("SELECT count(*) AS n FROM context_events").get() as { n: number }).n, 0);
    cleared.close();
  } finally { globalThis.fetch = originalFetch; }
});
